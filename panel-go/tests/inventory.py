#!/usr/bin/env python3
"""Generate Go contracts from the frozen JSON; optionally inspect a historical Git ref."""
from pathlib import Path
import argparse,json,re,subprocess
root=Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser();parser.add_argument('--from-git',metavar='REF');parser.add_argument('--check',action='store_true');options=parser.parse_args()
manifest=root/'panel-go/contracts/java-baseline.json'
if options.from_git:
 ref=subprocess.check_output(['git','-C',str(root),'rev-parse','--verify',options.from_git+'^{commit}'],text=True).strip()
 base=Path('springboot-backend/src/main/java/com/admin')
 def paths(part):
  raw=subprocess.check_output(['git','-C',str(root),'ls-tree','-rz','--name-only',ref,'--',str(base/part)])
  return [Path(p.decode()) for p in raw.split(b'\0') if p and p.endswith(b'.java')]
 def historical(p):return subprocess.check_output(['git','-C',str(root),'show',ref+':'+str(p)],text=True)
 routes=[]
 public={'/api/v1/user/login','/api/v1/config/get','/api/v1/open_api/sub_store'}
 read={'/api/v1/user/list','/api/v1/user/package','/api/v1/node/list','/api/v1/tunnel/list','/api/v1/tunnel/user/list','/api/v1/tunnel/user/tunnel','/api/v1/forward/list','/api/v1/speed-limit/list','/api/v1/speed-limit/tunnels','/api/v1/config/list','/api/v1/config/get','/api/v1/engine/audit','/api/v1/engine/bandwidth-groups','/api/v1/captcha/check','/api/v1/open_api/sub_store','/flow/test','/error'}
 for p in sorted(paths('controller')):
  s=re.sub(r'/\*.*?\*/','',historical(p),flags=re.S)
  parts=re.split(r'\bpublic\s+class\s+',s,maxsplit=1)
  if len(parts)!=2:continue
  h,b=parts;pre=re.findall(r'@RequestMapping\("([^"]*)"\)',h);pre=pre[-1] if pre else ''
  last=0
  for m in re.finditer(r'@(GetMapping|PostMapping|PutMapping|DeleteMapping|RequestMapping)\("([^"]*)"\)',b):
   start=b.find('{',m.end());end=start+1;depth=1
   # Controllers contain no braces inside string literals in method bodies that affect these boundaries.
   while depth and end<len(b):
    depth+=(b[end]=='{')-(b[end]=='}');end+=1
   annotations=b[last:start];sig=b[m.end():start];dto=re.search(r'\b(\w+Dto)\s+\w+',sig)
   path=pre+m[2]
   routes.append(dict(path=path,method={'GetMapping':'GET','PostMapping':'POST','PutMapping':'PUT','DeleteMapping':'DELETE','RequestMapping':'ANY'}[m[1]],admin='@RequireRole' in annotations,public=path in public or not path.startswith('/api/') or path.startswith('/api/v1/captcha/'),readOnly=path in read,dto=dto[1] if dto and ('@Validated' in sig or '@Valid ' in sig) else '',source=str(p)))
   last=end
 constraints={}
 for p in sorted(paths('common/dto')):
  s=re.sub(r'/\*.*?\*/','',historical(p),flags=re.S);fields=[];last=s.find('public class')
  for m in re.finditer(r'private\s+(\w+)\s+(\w+)\s*(?:=([^;]+))?;',s):
   annotations=s[last:m.start()];field=dict(name=m[2],type=m[1],rules=[])
   for rule in re.finditer(r'@(NotNull|NotBlank|Min|Max|DecimalMin)(?:\(([^)]*)\))?',annotations):
    args=rule[2] or '';msg=re.search(r'message\s*=\s*"([^"]*)"',args);value=re.search(r'(?:value\s*=\s*)?"?(-?[\d.]+)',args)
    field['rules'].append(dict(kind=rule[1],message=msg[1] if msg else field['name']+'参数无效',value=value[1] if value else ''))
   fields.append(field);last=m.end()
  constraints[p.stem]=fields
 if len(routes)!=64:raise SystemExit('Expected all 64 baseline mappings; refusing an incomplete inventory')
 data=dict(commit=ref,http=routes,dto=constraints)
 if options.check:
  frozen=json.loads(manifest.read_text())
  if (frozen['http'],frozen['dto'])!=(routes,constraints):raise SystemExit('Historical contract differs from frozen inventory')
 else:manifest.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n')
else:data=json.loads(manifest.read_text())
routes=data['http'];constraints=data['dto']
assert len(routes)==64 and len({r['path'] for r in routes})==64
q=json.dumps
code='// Code generated by tests/inventory.py from Java baseline; DO NOT EDIT.\npackage panel\n\ntype route struct{Method string;Admin,Public,ReadOnly bool;DTO string}\nvar routeByPath=map[string]route{\n'
for r in routes:code+=f'{q(r["path"])}:{{{q(r["method"])},{str(r["admin"]).lower()},{str(r["public"]).lower()},{str(r["readOnly"]).lower()},{q(r["dto"])}}},\n'
code+='}\ntype fieldRule struct{Field,Kind,Message,Value string}\nvar dtoRules=map[string][]fieldRule{\n'
for dto,fs in constraints.items():
 code+=q(dto)+':{\n'
 for f in fs:
  for r in f['rules']:code+='{'+','.join(q(x,ensure_ascii=False) for x in [f['name'],r['kind'],r['message'],r['value']])+'},\n'
 code+='},\n'
code+='}\n'
formatted=subprocess.check_output(['gofmt'],input=code,text=True)
output=root/'panel-go/internal/panel/contracts_generated.go'
if options.check:
 if output.read_text()!=formatted:raise SystemExit('Generated Go contracts are out of date')
else:output.write_text(formatted)
print(len(routes),'HTTP mappings checked' if options.check else 'HTTP mappings generated')
